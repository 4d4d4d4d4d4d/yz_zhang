"""IPC 知识产权归属与保密条款（52 号 spec）。

改造前合同模板只有四段：金额、验收、争议、性质声明。**没有知识产权归属，
也没有保密条款。**

后果按《著作权法》第十七条（委托作品）：受托人与委托人没有约定或者约定
不明的，**著作权属于受托人**。翻译成平台上的事实——发布方花 ¥3000 买了
一套 logo，著作权归执行方，他拿到的只是一份范围不明的使用许可。

而 `软件开发` 类目的发布模板里甚至写着 checklist「约定源码归属」：
**平台自己提示用户去约定，然后没有提供任何约定的地方。**
"""

# IPC-001 归属档位。**没有默认值**——发任务时必须选一个。
#
# 最容易犯的错是「默认归发布方」：那对执行方不公平，而且对通用组件、
# 含第三方素材的交付物直接就是错的。让当事人做一次选择，比替他们猜好。
IP_ASSIGNMENTS = ("assign", "license_exclusive", "license_nonexclusive", "retain")

IP_LABELS = {
    "assign": "著作权转让",
    "license_exclusive": "独占许可",
    "license_nonexclusive": "普通许可",
    "retain": "执行方保留",
}

# IPC-003 人身权依法不可转让。
#
# 把「著作权全部转让」写进合同是一句**无效**的话，而写无效的话比不写更糟：
# 当事人会以为自己拿到了实际上没有的东西，到用的时候才发现不是。
_MORAL_RIGHTS_NOTE = (
    "署名权、修改权、保护作品完整权等著作人身权依法不得转让，"
    "仍归执行方享有；发布方使用交付成果时应为执行方署名，"
    "双方另有书面约定的除外。"
)

_IP_CLAUSES = {
    "assign": (
        "知识产权: 交付成果的著作财产权（含复制、发行、信息网络传播、改编等）"
        "自发布方付清全部价款之日起转让给发布方；执行方保证其对交付成果享有"
        "完整权利且不侵犯第三方权利。" + _MORAL_RIGHTS_NOTE
    ),
    "license_exclusive": (
        "知识产权: 交付成果的著作权仍归执行方，执行方授予发布方**独占**使用权"
        "（执行方本人亦不得再行使用于相同用途），地域与期限不限，"
        "但执行方可将其用于个人作品集展示。" + _MORAL_RIGHTS_NOTE
    ),
    "license_nonexclusive": (
        "知识产权: 交付成果的著作权仍归执行方，执行方授予发布方**普通**使用权；"
        "执行方可另行许可他人使用。" + _MORAL_RIGHTS_NOTE
    ),
    "retain": (
        "知识产权: 交付成果的著作权归执行方所有，发布方仅在本任务约定的"
        "用途与范围内使用，超出范围需另行书面授权。" + _MORAL_RIGHTS_NOTE
    ),
}

# IPC-002 保密**双向**。只约束一方的保密条款在谈判上站不住，在履行上也不公平。
CONFIDENTIALITY_CLAUSE = (
    "保密: 双方对因本任务获知的对方非公开信息负保密义务，"
    "期限自知悉之日起三年。发布方侧包括但不限于客户资料、账号口令、"
    "未公开的经营与产品计划；执行方侧包括但不限于报价依据、未被采用的方案。"
    "下列情形不属违约: (一)信息已公开且非因接收方原因; "
    "(二)接收方独立开发或合法自第三方取得; "
    "(三)依法律、法规或有权机关要求披露，但应在允许范围内事先通知对方。"
)

# IPC-050 **不假装这是律师起草的正式合同文本。**
TEMPLATE_NOTICE = (
    "说明: 本合同由平台模板生成，供双方达成合意之用；"
    "涉及重大金额或复杂权利安排时，建议另行咨询执业律师。"
)


def ip_clause(assignment: str) -> str:
    if assignment not in _IP_CLAUSES:
        raise ValueError(f"未知的知识产权归属档位：{assignment!r}")
    return _IP_CLAUSES[assignment]


def outcome_clause(base_cents: int, bonus_cents: int, criteria: list) -> str:
    """OUT-001/002 浮动对价条款。

    必须写清楚三件事，否则它就是一句口头承诺：浮动**上限**是多少、
    达标的**客观判据**是什么、**谁来判**。
    """
    lines = [
        f"浮动对价: 基础报酬 {base_cents / 100:.2f} 元；"
        f"达到下列全部验收指标的，另行加付 {bonus_cents / 100:.2f} 元"
        f"（**上限即此数，不随任何收益浮动**）。",
        "加付部分已与基础报酬一并托管；未达标的，加付部分原路退回发布方。",
        "达标判定: 标注为「平台判定」的指标由平台按客观规则执行，"
        "任一方均不得覆盖；标注为「人工确认」的指标由发布方确认，"
        "不予确认的应说明理由，执行方有异议可依争议解决条款处理。",
    ]
    for i, c in enumerate(criteria or [], 1):
        kind = "平台判定" if c.get("kind") == "auto" else "人工确认"
        lines.append(f"  {i}. [{kind}] {c.get('text', '')}")
    return "\n".join(lines)
